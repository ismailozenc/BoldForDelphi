CREATE TABLE BOLD_ID (  BOLD_ID INTEGER  NOT NULL);
CREATE TABLE BOLD_TYPE (  BOLD_TYPE SMALLINT  NOT NULL, 
  CLASSNAME VARCHAR(255)  NOT NULL);
CREATE TABLE BOLD_XFILES (  BOLD_ID INTEGER  NOT NULL, 
  BOLD_TYPE SMALLINT  NOT NULL, 
  EXTERNAL_ID VARCHAR(255)  NOT NULL, 
  BOLD_TIME_STAMP INTEGER  NOT NULL, 
  CONSTRAINT IX_BOLD_XFILES_BOLD_ID PRIMARY KEY (BOLD_ID));
CREATE TABLE BOLD_TABLES (  TABLENAME VARCHAR(255)  NOT NULL);
CREATE TABLE BOLD_TIMESTAMP (  BOLD_TIME_STAMP INTEGER  NOT NULL);
CREATE TABLE BOLD_LASTCLOCK (  LastTimestamp INTEGER  NOT NULL, 
  LastClockTime DATETIME  NOT NULL);
CREATE TABLE BOLD_CLOCKLOG (  LastTimestamp INTEGER  NOT NULL, 
  ThisTimestamp INTEGER  NOT NULL, 
  LastClockTime DATETIME  NOT NULL, 
  ThisClockTime DATETIME  NOT NULL);
CREATE TABLE BOLD_MEMBERMAPPING (  CLASSNAME VARCHAR(60)  NOT NULL, 
  MEMBERNAME VARCHAR(60)  NOT NULL, 
  TABLENAME VARCHAR(60)  NOT NULL, 
  COLUMNS VARCHAR(60)  NOT NULL, 
  MAPPERNAME VARCHAR(60)  NOT NULL);
CREATE TABLE BOLD_R_CLSMAP (  CLASSNAME VARCHAR(60)  NOT NULL, 
  TABLENAME VARCHAR(60)  NOT NULL, 
  CLASSIDREQUIRED INTEGER  NOT NULL);
CREATE TABLE BOLD_W_CLSMAP (  CLASSNAME VARCHAR(60)  NOT NULL, 
  TABLENAME VARCHAR(60)  NOT NULL);
CREATE TABLE BOLD_OBJECT (  BOLD_ID INTEGER  NOT NULL, 
  BOLD_TYPE SMALLINT  NOT NULL, 
  READ_ONLY INTEGER  NOT NULL, 
  CONSTRAINT IX_BOLD_OBJECT_BOLD_ID PRIMARY KEY (BOLD_ID));
CREATE  INDEX IX_BOLD_OBJECT_BOLD_TYPE ON BOLD_OBJECT (BOLD_TYPE);
CREATE TABLE Building (  BOLD_ID INTEGER  NOT NULL, 
  BOLD_TYPE SMALLINT  NOT NULL, 
  ZipCode INTEGER DEFAULT 0 NOT NULL, 
  Address VARCHAR(255) DEFAULT '' NOT NULL, 
  CONSTRAINT IX_Building_BOLD_ID PRIMARY KEY (BOLD_ID));
CREATE  INDEX IX_Building_BOLD_TYPE ON Building (BOLD_TYPE);
CREATE TABLE Ownership (  BOLD_ID INTEGER  NOT NULL, 
  BOLD_TYPE SMALLINT  NOT NULL, 
  OwnedBuildings INTEGER DEFAULT -1 , 
  OwnedBuildings_O INTEGER DEFAULT -1 , 
  Owners INTEGER DEFAULT -1 , 
  Owners_O INTEGER DEFAULT -1 , 
  CONSTRAINT IX_Ownership_BOLD_ID PRIMARY KEY (BOLD_ID));
CREATE  INDEX IX_Ownership_BOLD_TYPE ON Ownership (BOLD_TYPE);
CREATE  INDEX IX_Ownership_OwnedBuildings ON Ownership (OwnedBuildings);
CREATE  INDEX IX_Ownership_OwnedBuildings_O ON Ownership (OwnedBuildings_O);
CREATE  INDEX IX_Ownership_Owners ON Ownership (Owners);
CREATE  INDEX IX_Ownership_Owners_O ON Ownership (Owners_O);
CREATE TABLE Person (  BOLD_ID INTEGER  NOT NULL, 
  BOLD_TYPE SMALLINT  NOT NULL, 
  FirstName VARCHAR(255) DEFAULT '' NOT NULL, 
  LastName VARCHAR(25) DEFAULT '' NOT NULL, 
  Assets NUMERIC DEFAULT 0 NOT NULL, 
  IsMarried INTEGER DEFAULT 0 NOT NULL, 
  Home INTEGER DEFAULT -1 , 
  Home_O INTEGER DEFAULT -1 , 
  CONSTRAINT IX_Person_BOLD_ID PRIMARY KEY (BOLD_ID));
CREATE  INDEX IX_Person_BOLD_TYPE ON Person (BOLD_TYPE);
CREATE  INDEX IX_Person_Home ON Person (Home);
CREATE  INDEX IX_Person_Home_O ON Person (Home_O);
CREATE TABLE Residential_Building (  BOLD_ID INTEGER  NOT NULL, 
  BOLD_TYPE SMALLINT  NOT NULL, 
  TotalRent NUMERIC DEFAULT 0 NOT NULL, 
  CONSTRAINT IX_Residential_Building_BOLD_ID PRIMARY KEY (BOLD_ID));
CREATE  INDEX IX_Residential_Building_BOLD_TYPE ON Residential_Building (BOLD_TYPE);
