    /// <summary>The name as a C# identifier: a C# keyword gets an @ in front.</summary>
    public static string Identifier(string name) => CSharpKeywords.Contains(name) ? "@" + name : name;

    /// <summary>The C# type of a Delphi type: a model class stays (nullable when <paramref name="nullableClass"/>), a known type is translated.</summary>
    public string CSharpType(string DelphiType, bool nullableClass = true)
    {
        string type = DelphiType.Trim().TrimEnd('*').Trim();
        if (Model?.Classes.ItemsByDelphiName(type) is not null || Model?.Classes.ItemsByExpressionName(type) is { })
        {
            string name = Model.Classes.ItemsByDelphiName(type)?.ExpandedDelphiName ?? Model.Classes.ItemsByExpressionName(type)!.ExpandedDelphiName;
            return nullableClass ? name + "?" : name;
        }

        return NativeTypes.TryGetValue(type, out string? cs) ? cs : type;
    }

    /// <summary>The visibility keyword of a Delphi visibility.</summary>
    private static string Visibility(TVisibilityKind Visibility) => Visibility switch
    {
        TVisibilityKind.vkPrivate => "private",
        TVisibilityKind.vkProtected => "protected",
        _ => "public",
    };

    /// <summary>The highest class above <paramref name="MoldClass"/> that declares a method with the name, or null.</summary>
    private static TMoldMethod? DeclarationAbove(TMoldClass MoldClass, string Name)
    {
        TMoldMethod? result = null;
        for (TMoldClass? c = MoldClass.SuperClass; c is not null; c = c.SuperClass)
        {
            for (int i = 0; i < c.Methods.Count; i++)
            {
                if (SysUtils.SameText(c.Methods[i].Name, Name))
                {
                    result = c.Methods[i];
                }
            }
        }

        return result;
    }

    /// <summary>The overridable method of TBoldObject (or its base classes) with the name and parameter count, or null.</summary>
    private static MethodInfo? FrameworkMethod(string Name, int ParameterCount) =>
        typeof(TBoldObject).GetMethods(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic)
            .Where(m => string.Equals(m.Name, Name, StringComparison.OrdinalIgnoreCase) && m.IsVirtual && !m.IsFinal &&
                        (m.IsPublic || m.IsFamily || m.IsFamilyOrAssembly) && m.GetParameters().Length == ParameterCount)
            .Select(m => m.GetBaseDefinition())
            .FirstOrDefault();

    /// <summary>A C# header and the call of its base method, of a method declared in C# (in TBoldObject).</summary>
    private static (string header, string call, bool hasResult) FrameworkHeader(MethodInfo method, bool partial)
    {
        var nullability = new NullabilityInfoContext();
        string access = method.IsPublic ? "public" : "protected";
        string result = TypeName(method.ReturnType, nullability.Create(method.ReturnParameter));
        var parameters = new List<string>();
        var arguments = new List<string>();
        foreach (ParameterInfo p in method.GetParameters())
        {
            Type type = p.ParameterType.IsByRef ? p.ParameterType.GetElementType()! : p.ParameterType;
            string modifier = p.ParameterType.IsByRef ? p.IsOut ? "out " : "ref " : p.GetCustomAttribute<ParamArrayAttribute>() is not null ? "params " : "";
            string name = Identifier(p.Name!);
            parameters.Add(modifier + TypeName(type, nullability.Create(p)) + " " + name);
            arguments.Add(modifier.Replace("params ", "", StringComparison.Ordinal) + name);
        }

        string header = $"{access} override {(partial ? "partial " : "")}{result} {method.Name}({string.Join(", ", parameters)})";
        bool hasResult = method.ReturnType != typeof(void);
        string call = (hasResult ? "return " : "") + $"base.{method.Name}({string.Join(", ", arguments)})";
        return (header, call, hasResult);
    }

    /// <summary>The C# name of a .NET type, with nullable reference types marked.</summary>
    private static string TypeName(Type type, NullabilityInfo? nullability)
    {
        string name;
        if (type == typeof(void))
        {
            return "void";
        }

        if (Nullable.GetUnderlyingType(type) is { } underlying)
        {
            return TypeName(underlying, null) + "?";
        }

        if (type.IsArray)
        {
            name = TypeName(type.GetElementType()!, nullability?.ElementType) + "[]";
        }
        else if (type.IsEnum)
        {
            name = type.Namespace == "Bold" ? type.Name : "global::" + type.FullName!.Replace('+', '.');
        }
        else
        {
            name = Type.GetTypeCode(type) switch
            {
                TypeCode.Boolean => "bool", TypeCode.Byte => "byte", TypeCode.SByte => "sbyte", TypeCode.Int16 => "short",
                TypeCode.UInt16 => "ushort", TypeCode.Int32 => "int", TypeCode.UInt32 => "uint", TypeCode.Int64 => "long",
                TypeCode.UInt64 => "ulong", TypeCode.Single => "float", TypeCode.Double => "double", TypeCode.Decimal => "decimal",
                TypeCode.Char => "char", TypeCode.String => "string",
                _ => type == typeof(object) ? "object" : type.Namespace == "Bold" ? type.Name.Split('`')[0] : "global::" + type.FullName!.Replace('+', '.'),
            };
        }

        return !type.IsValueType && nullability?.ReadState == NullabilityState.Nullable ? name + "?" : name;
    }

    /// <summary>The C# parameters of a model method, and the arguments to pass them on.</summary>
    private (string parameters, string arguments) ModelSignature(TMoldMethod Method)
    {
        var parameters = new List<string>();
        var arguments = new List<string>();
        for (int i = 0; i < Method.Parameters.Count; i++)
        {
            var p = (TMoldParameter)Method.Parameters[i]!;
            string modifier = p.ParameterKind switch
            {
                TBoldParameterDirectionKind.pdInout => "ref ",
                TBoldParameterDirectionKind.pdOut => "out ",
                _ => "",
            };
            string name = Identifier(p.ParameterName);
            parameters.Add(modifier + CSharpType(p.DelphiParameterType) + " " + name);
            arguments.Add(modifier + name);
        }

        return (string.Join(", ", parameters), string.Join(", ", arguments));
    }

    /// <summary>
    /// The C# method of a model method: its header, the call of the inherited method (null when there is none), and
    /// whether it returns a value. An override of a TBoldObject method takes that method's C# signature; an override of a
    /// method of a superclass takes that method's visibility. Methods are partial, so their bodies go in the user file;
    /// abstract methods have a body that throws.
    /// </summary>
    public (string header, string? inheritedCall, bool hasResult, bool isAbstract) MethodToCSharp(TMoldClass OwningClass, TMoldMethod Method, bool AutoOverride)
    {
        bool overrides = AutoOverride || Method.FuncType == TDelphiFunctionType.dfOverride;
        TMoldMethod? above = DeclarationAbove(OwningClass, Method.Name);
        // An override with no method to override in a superclass or in TBoldObject starts the chain: it is virtual.
        bool startsChain = false;
        if (overrides && !Method.IsClassMethod)
        {
            TMoldMethod? root = above;
            if (root is null || root.FuncType == TDelphiFunctionType.dfOverride)
            {
                MethodInfo? framework = FrameworkMethod(Method.ExpandedDelphiName, root?.Parameters.Count ?? Method.Parameters.Count);
                if (framework is not null)
                {
                    (string header, string call, bool hasResult) = FrameworkHeader(framework, true);
                    return (header, call, hasResult, false);
                }

                startsChain = root is null;
            }
        }

        (string parameters, string arguments) = ModelSignature(Method);
        string result = Method.HasReturnValue ? CSharpType(Method.DelphiReturnType) : "void";
        // Delphi ignores case: an override takes the name of the method it overrides.
        string name = Identifier((overrides && above is not null ? above : Method).ExpandedDelphiName);
        string access = Visibility(Method.Visibility);
        string modifiers;
        string? inherited = null;
        bool isAbstract = false;
        if (Method.IsClassMethod)
        {
            modifiers = "static partial";
        }
        else if (overrides && above is not null)
        {
            access = Visibility(above.Visibility);
            modifiers = "override partial";
            inherited = (Method.HasReturnValue ? "return " : "") + $"base.{name}({arguments})";
        }
        else if (Method.FuncType == TDelphiFunctionType.dfAbstractVirtual)
        {
            modifiers = "virtual";
            isAbstract = true;
        }
        else if (startsChain || Method.FuncType is TDelphiFunctionType.dfVirtual or TDelphiFunctionType.dfDynamic || Method.OverrideInAllSubclasses)
        {
            modifiers = "virtual partial";
        }
        else
        {
            modifiers = "partial";
        }

        return ($"{access} {modifiers} {result} {name}({parameters})", inherited, Method.HasReturnValue, isAbstract);
    }

    /// <summary>
    /// The declaration of a method in the generated class (publicTag, protectedTag, PrivateTag), or the header of its
    /// implementation in the user file (ImplementationTag).
    /// </summary>
    public override string MethodToCodeHeader(TMoldClass OwningClass, TMoldMethod Method, int TagValue, bool AddSignature, bool AutoOverride)
    {
        (string header, _, _, bool isAbstract) = MethodToCSharp(OwningClass, Method, AutoOverride);
        if (TagValue == ImplementationTag)
        {
            return header;
        }

        return isAbstract
            ? $"{header} => throw new global::System.NotSupportedException(\"{OwningClass.ExpandedDelphiName}.{Method.ExpandedDelphiName} is abstract.\");"
            : header + ";";
    }

    /// <summary>
    /// The statement that calls the inherited method, for the user file stub; it also sets the stub's default body
    /// (DEFAULTBODY of the method template): a throw for a method with a result, else nothing.
    /// </summary>
    public override string GenerateInheritedCall(TMoldClass MoldClass, TMoldMethod MoldMethod)
    {
        // The base generator calls this for the class's own methods and for the methods it overrides automatically
        // (those of a superclass marked OverrideInAllSubclasses).
        (_, string? inherited, bool hasResult, _) = MethodToCSharp(MoldClass, MoldMethod, MoldMethod.MoldClass != MoldClass);
        fMethodTemplate.Variables.SetVariable("DEFAULTBODY", hasResult ? NotImplementedBody : "");
        return inherited ?? (hasResult ? "throw new global::System.NotImplementedException()" : "// no inherited method");
    }

    /// <summary>Whether a native attribute's accessor methods are protected virtual (else private).</summary>
    private bool AccessorIsVirtual(string ClassName, string AttributeName, bool read)
    {
        TMoldClass? c = Model?.Classes.ItemsByDelphiName(ClassName);
        for (int i = 0; c is not null && i < c.AllNativeAttributes.Count; i++)
        {
            if (c.AllNativeAttributes[i].ExpandedDelphiName == AttributeName)
            {
                return (read ? c.AllNativeAttributes[i].DelphiPropertyRead : c.AllNativeAttributes[i].DelphiPropertyWrite) == TDelphiPropertyAccessKind.pkProtectedVirtualMethod;
            }
        }

        return false;
    }

    public override string ReadMethodSignature(string ClassName, string AttributeName, string AttributeType)
    {
        fMethodTemplate.Variables.SetVariable("DEFAULTBODY", NotImplementedBody);
        return $"{(AccessorIsVirtual(ClassName, AttributeName, true) ? "protected virtual" : "private")} partial {CSharpType(AttributeType)} Get{AttributeName}()";
    }

    public override string WriteMethodSignature(string ClassName, string AttributeName, string AttributeType)
    {
        fMethodTemplate.Variables.SetVariable("DEFAULTBODY", "");
        return $"{(AccessorIsVirtual(ClassName, AttributeName, false) ? "protected virtual" : "private")} partial void Set{AttributeName}({CSharpType(AttributeType)} NewValue)";
    }

    /// <summary>A line with a method header: a partial method, an override or a void method.</summary>
    public override bool StringContainsMethodHeader(string s) =>
        s.Contains('(') && (s.Contains(" partial ", StringComparison.Ordinal) || s.Contains(" override ", StringComparison.Ordinal) || s.Contains(" void ", StringComparison.Ordinal));

    /// <summary>The method's name followed by "(" (with the parameters when they are searched for too).</summary>
    public override string GetSearchStringfromMethodHeader(string header, bool SearchParameterList)
    {
        int open = header.IndexOf('(', StringComparison.Ordinal);
        if (open < 0)
        {
            return header;
        }

        int start = open;
        while (start > 0 && (char.IsLetterOrDigit(header[start - 1]) || header[start - 1] is '_' or '@'))
        {
            start--;
        }

        return " " + (SearchParameterList ? header[start..] : header[start..(open + 1)]);
    }

    public override void AddQualifierPropertyParam(ref string Params, string ParamName, string ParamType) => AddQualifierFunctionParam(ref Params, ParamName, ParamType);

    public override void AddQualifierFunctionParam(ref string Params, string ParamName, string ParamType)
    {
        if (Params != "")
        {
            Params += ", ";
        }

        Params += CSharpType(ParamType) + " " + Identifier(ParamName);
    }
}

/// <summary>
/// The generator for C#: one file per class (DECIDE-5) besides the per-component registration file, C# names for
/// native types, and user files of one class each whose methods go inside the class.
/// </summary>
public class TBoldCSharpGenerator : TBoldGenerator
{
    private TMoldClass? fFileClass;

    /// <summary>A generator with the C# templates installed and typed lists.</summary>
    public TBoldCSharpGenerator(TBoldTypeNameDictionary TypeNameDictionary)
        : base(TypeNameDictionary)
    {
        TBoldCSharpTemplateManager.InstallTemplates();
        UseTypedLists = true;
    }

    private static TBoldCSharpTemplateManager Manager => (TBoldCSharpTemplateManager)BoldGeneratorTemplatesManager();

    /// <summary>Generates the classes (one file each) and the component files, and adds the missing method stubs.</summary>
    public void Generate()
    {
        System.Text.Encoding? encoding = BoldFileHandler.FileEncoding;
        BoldFileHandler.FileEncoding = new System.Text.UTF8Encoding(false);
        try
        {
            GenerateBusinessObjectCode();
            EnsureMethodImplementations();
            BoldFileHandler.BoldCloseAllFilehandlers();
        }
        finally
        {
            BoldFileHandler.FileEncoding = encoding;
        }
    }

    /// <summary>Expands the component templates (registration), then the class templates once for each class.</summary>
    public override void ExpandTemplateList(TBoldTemplateList TemplateList)
    {
        Manager.Model = MoldModel;
        base.ExpandTemplateList(TemplateList);
        if (TemplateList != Manager.FileTemplates)
        {
            return;
        }

        for (int c = 0; c < MoldModel.Classes.Count; c++)
        {
            TMoldClass moldClass = MoldModel.Classes[c];
            for (int t = 0; t < Manager.ClassTemplates.Count; t++)
            {
                TBoldTemplateHolder template = Manager.ClassTemplates[t];
                template.Variables.SetVariable("CLASSEXPRESSIONNAME", moldClass.ExpandedExpressionName);
                string fileName = template.ExpandedFileName;
                SetCurrentFileHandler(BaseFilePath, fileName, TBoldModuleType.mtText, true, false);
                BoldFilehandler!.Clear();
                fFileClass = moldClass;
                try
                {
                    InitializeTemplateForComponent(template, MoldModel, moldClass.Component, true);
                }
                finally
                {
                    fFileClass = null;
                }

                BoldFilehandler.AddStrings(template.ExpandedTemplate);
            }
        }
    }

    /// <summary>When a class file is expanded, only its class.</summary>
    protected override bool ClassInTemplate(TMoldClass MoldClass, TMoldComponent Component) =>
        fFileClass is not null ? MoldClass == fFileClass : base.ClassInTemplate(MoldClass, Component);

    /// <summary>
    /// The variables of the base generator, with C# types and identifiers: native types in C#, C# keywords escaped
    /// (CSMEMBERNAME, CSQUALIFIERNAME, CSDelphiAttributeName), every component as COMPONENT.n, and the class of the user
    /// file (CLASSNAME) for its header.
    /// </summary>
    protected override void InitializeTemplateForComponent(TBoldTemplateHolder Template, TMoldModel Model, TMoldComponent Component, bool InitializeClasses)
    {
        Manager.Model = MoldModel;
        base.InitializeTemplateForComponent(Template, Model, Component, InitializeClasses);
        TBoldTemplateVariables variables = Template.Variables;
        var extra = new List<(string name, string value)>();
        using (TBoldIndexableListTraverser traverser = variables.CreateTraverser()!)
        {
            while (!traverser.EndOfList)
            {
                var variable = (TBoldTemplateVariable)traverser.Item!;
                string name = variable.Name;
                if (name.StartsWith("MEMBERNATIVETYPE.", StringComparison.Ordinal) || name.StartsWith("DelphiAttributeType.", StringComparison.Ordinal))
                {
                    variable.Value = Manager.CSharpType(variable.Value, false);
                }
                else if (name.StartsWith("MEMBERNAME.", StringComparison.Ordinal) || name.StartsWith("QUALIFIERNAME.", StringComparison.Ordinal) || name.StartsWith("DelphiAttributeName.", StringComparison.Ordinal))
                {
                    extra.Add(("CS" + name, TBoldCSharpTemplateManager.Identifier(variable.Value)));
                }
                else if (name.StartsWith("DelphiAttributeVisibility.", StringComparison.Ordinal))
                {
                    variable.Value = "public";
                }

                traverser.Next();
            }
        }

        foreach ((string name, string value) in extra)
        {
            variables.ForceAdd(name, value, DelphiSet<int>.Empty);
        }

        variables.ForceAdd("COMPONENTCOUNT", SysUtils.IntToStr(Model.Components.Count), DelphiSet<int>.Empty);
        for (int i = 0; i < Model.Components.Count; i++)
        {
            variables.ForceAdd("COMPONENT." + SysUtils.IntToStr(i), Model.Components[i].Name, DelphiSet<int>.Empty);
        }

        if (fFileClass is not null)
        {
            variables.ForceAdd("USERFILE", IncFileNameForClass(fFileClass), DelphiSet<int>.Empty);
        }

        if (Template == Manager.IncFileHeaderTemplate && (TMoldClass?)CurrentClass is { } current)
        {
            variables.ForceAdd("CLASSNAME", current.ExpandedDelphiName, DelphiSet<int>.Empty);
            variables.SetVariable("UNITNAME", current.Component.Name);
        }
    }

    /// <summary>The user file of a class: the name of its FileName tagged value when set (with .cs), else &lt;Class&gt;.cs.</summary>
    protected override string IncFileNameForClass(TMoldClass MoldClass) =>
        MoldClass.IncFileName != ""
            ? Path.ChangeExtension(MoldClass.EffectiveIncFileName(Manager.DefaultIncFileExtension), Manager.DefaultIncFileExtension)
            : MoldClass.ExpandedExpressionName + Manager.DefaultIncFileExtension;

    /// <summary>
    /// Adds the method to the current class's partial class in the user file, unless the class already has a method
    /// with the name (searched ignoring case, as Delphi does); a file without the class gets a partial class for it.
    /// </summary>
    protected override void EnsureMethod(TStrings Strings)
    {
        TBoldFileHandler file = BoldFilehandler!;
        var lines = new List<string>();
        for (int i = 0; i < file.Count; i++)
        {
            lines.Add(file.Content(i));
        }

        string search = SysUtils.UpperCase(Manager.GetSearchStringfromMethodHeader(Strings[0], false));
        (int start, int end) = ClassBlock(lines, CurrentClass.ExpandedDelphiName);
        if (start < 0)
        {
            lines.Add("");
            lines.Add("public partial class " + CurrentClass.ExpandedDelphiName);
            lines.Add("{");
            lines.Add("}");
            (start, end) = ClassBlock(lines, CurrentClass.ExpandedDelphiName);
        }

        for (int i = start; i < end; i++)
        {
            if (SysUtils.Pos(search, SysUtils.UpperCase(lines[i])) != 0)
            {
                return;
            }
        }

        var method = new List<string>();
        if (end > 0 && SysUtils.Trim(lines[end - 1]) != "{")
        {
            method.Add("");
        }

        for (int i = 0; i < Strings.Count; i++)
        {
            method.Add(Strings[i] == "" ? "" : "    " + Strings[i]);
        }

        lines.InsertRange(end, method);
        file.ModifyContents(string.Join(BoldDefs.BOLDCRLF, lines), true);
    }

    /// <summary>The lines of the class's partial class: from its declaration to its closing brace (exclusive), or (-1, -1).</summary>
    private static (int start, int end) ClassBlock(List<string> lines, string className)
    {
        var declaration = new System.Text.RegularExpressions.Regex(@"\bpartial\s+class\s+" + System.Text.RegularExpressions.Regex.Escape(className) + @"\b");
        for (int i = 0; i < lines.Count; i++)
        {
            if (!declaration.IsMatch(lines[i]))
            {
                continue;
            }

            int depth = 0;
            bool opened = false;
            for (int j = i; j < lines.Count; j++)
            {
                foreach (char ch in lines[j])
                {
                    if (ch == '{')
                    {
                        depth++;
                        opened = true;
                    }
                    else if (ch == '}')
                    {
                        depth--;
                        if (opened && depth == 0)
                        {
                            return (i, j);
                        }
                    }
                }
            }
        }

        return (-1, -1);
    }
}
