        /// <summary>A C# string literal.</summary>
        public static string Literal(string value)
        {
            var sb = new StringBuilder("\"");
            foreach (char c in value)
            {
                switch (c)
                {
                    case '"':
                        sb.Append("\\\"");
                        break;
                    case '\\':
                        sb.Append("\\\\");
                        break;
                    case '\n':
                        sb.Append("\\n");
                        break;
                    case '\r':
                        sb.Append("\\r");
                        break;
                    case '\t':
                        sb.Append("\\t");
                        break;
                    default:
                        if (c < ' ')
                        {
                            sb.Append("\\u").Append(((int)c).ToString("x4"));
                        }
                        else
                        {
                            sb.Append(c);
                        }

                        break;
                }
            }

            return sb.Append('"').ToString();
        }

        /// <summary>Lines with braces that indent.</summary>
        private sealed class CodeWriter
        {
            private readonly StringBuilder fText = new StringBuilder();
            private int fIndent;

            public void Line(string text = "")
            {
                if (text.Length > 0)
                {
                    fText.Append(' ', fIndent * 4);
                }

                fText.Append(text).Append('\n');
            }

            public void Open()
            {
                Line("{");
                fIndent++;
            }

            public void Close() => CloseWith("}");

            public void CloseWith(string text)
            {
                fIndent--;
                Line(text);
            }

            public override string ToString() => fText.ToString();
        }
    }
