// The code the generator writes, after Delphi's attribute wizard's templates (BoldWAdmTemplates): ValueSetTemplate,
// AttributeTemplate with InterfaceTemplate and MapperTemplate, and SubClassedAttrTemplate. Where the templates left a
// method body to the user ("your code here"), the user writes the method in the partial class; what the templates
// wrote in full, the generator writes, in C# and against the C# port's API.
using System.Text;

namespace Bold.SourceGenerators
{
    /// <summary>Writes the source of a marked class.</summary>
    public static class BoldAttributeCode
    {
        /// <summary>The source of the rest of the class (and the types that go with it).</summary>
        public static string Write(BoldAttributeSpec spec)
        {
            var w = new CodeWriter();
            w.Line("// <auto-generated>");
            w.Line($"//   Written by the Bold attribute generator (Bold.SourceGenerators) from the attributes on {spec.ClassName}, as Delphi's");
            w.Line("//   attribute wizard wrote an attribute unit. Changes are lost when the project builds again.");
            w.Line("// </auto-generated>");
            w.Line("#nullable enable");
            w.Line("#pragma warning disable CA2255, CS0108, CS0114, CS1591");
            w.Line();
            if (spec.Namespace.Length > 0)
            {
                w.Line($"namespace {spec.Namespace};");
                w.Line();
            }

            switch (spec.Kind)
            {
                case BoldAttributeKind.ValueSet:
                    WriteValueSet(w, spec);
                    break;
                case BoldAttributeKind.NewAttribute:
                    WriteNewAttribute(w, spec);
                    break;
                default:
                    WriteSubclassedAttribute(w, spec);
                    break;
            }

            return w.ToString();
        }

        // ValueSetTemplate: the enumeration, the property As<Name>, the values and the registration.
        private static void WriteValueSet(CodeWriter w, BoldAttributeSpec spec)
        {
            string values = "_" + spec.ExpressionName + "Values";
            w.Line($"/// <summary>The values of the value set {spec.ExpressionName}.</summary>");
            w.Line($"{spec.Accessibility} enum {spec.EnumName}");
            w.Open();
            foreach (BoldValueSpec value in spec.Values)
            {
                w.Line($"{spec.ValuePrefix}{value.Name},");
            }

            w.Close();
            w.Line();
            w.Line($"partial class {spec.ClassName}");
            w.Open();
            w.Line($"private static global::Bold.TBAValueSetValueList? {values};");
            w.Line();
            w.Line($"/// <summary>The value as a member of {spec.EnumName}.</summary>");
            w.Line($"public {spec.EnumName} As{spec.ExpressionName}");
            w.Open();
            w.Line($"get => ({spec.EnumName})AsInteger;");
            w.Line("set => AsInteger = (int)value;");
            w.Close();
            w.Line();
            w.Line($"/// <summary>The values of {spec.ExpressionName}, each with its string representations, made once.</summary>");
            w.Line("protected override global::Bold.TBAValueSetValueList GetValues()");
            w.Open();
            w.Line($"if ({values} is null)");
            w.Open();
            w.Line("var values = new global::Bold.TBAValueSetValueList();");
            foreach (BoldValueSpec value in spec.Values)
            {
                string representations = string.Join(", ", value.Representations.Select(Literal));
                w.Line($"values.Add((int){spec.EnumName}.{spec.ValuePrefix}{value.Name}, {representations});");
            }

            w.Line($"{values} = values;");
            w.Close();
            w.Line();
            w.Line($"return {values};");
            w.Close();
            WriteTypeNameMapping(w, spec, spec.ContentName, spec.MapperName, "As<Name>", "T<Name>Enum");
            WriteRegistration(w, spec, null);
            w.Close();
        }

        // SubClassedAttrTemplate: what is left for the generator is the registration; the type takes the superclass's
        // content and persistence, so its type name mapping copies the superclass's.
        private static void WriteSubclassedAttribute(CodeWriter w, BoldAttributeSpec spec)
        {
            w.Line($"partial class {spec.ClassName}");
            w.Open();
            w.Line($"/// <summary>");
            w.Line($"/// Adds the type to a type name dictionary (a model's), as Delphi's wizard told you to add it to the TypeNameHandle:");
            w.Line($"/// the content, persistence mapper, accessor and native type of {spec.SuperClassName}'s mapping, unless the attribute says otherwise.");
            w.Line($"/// </summary>");
            w.Line("public static global::Bold.TBoldTypeNameMapping AddTypeNameMapping(global::Bold.TBoldTypeNameDictionary Dictionary)");
            w.Open();
            w.Line("global::Bold.TBoldTypeNameMapping? super = null;");
            w.Line("for (int i = 0; i < Dictionary.Count && super is null; i++)");
            w.Open();
            w.Line($"if (Dictionary.Mapping(i) is {{ }} m && (m.DelphiName == {Literal(spec.SuperClassName)} || m.ExpandedDelphiName == {Literal(spec.SuperClassName)}))");
            w.Open();
            w.Line("super = m;");
            w.Close();
            w.Close();
            w.Line();
            w.Line("global::Bold.TBoldTypeNameMapping mapping = Dictionary.AddMapping();");
            w.Line("if (super is not null)");
            w.Open();
            w.Line("super.AssignTo(mapping);");
            w.Line("mapping.ContentsName = super.ExpandedContentsName;");
            w.Line("mapping.MapperName = super.ExpandedMapperName;");
            w.Line("mapping.NativeType = super.ExpandedNativeType;");
            w.Line("mapping.Accessor = super.ExpandedAccessor;");
            w.Close();
            w.Line();
            w.Line($"mapping.ModelName = {Literal(spec.ModelName)};");
            w.Line($"mapping.ExpressionName = {Literal(spec.ExpressionName)};");
            w.Line($"mapping.DelphiName = {Literal(spec.ClassName)};");
            if (spec.ContentName.Length > 0)
            {
                w.Line($"mapping.ContentsName = {Literal(spec.ContentName)};");
            }

            if (spec.MapperName.Length > 0)
            {
                w.Line($"mapping.MapperName = {Literal(spec.MapperName)};");
            }

            w.Line($"mapping.UnitNameText = {Literal(spec.Namespace)};");
            w.Line("return mapping;");
            w.Close();
            WriteRegistration(w, spec, null);
            w.Close();
        }

        // AttributeTemplate (interfaced), InterfaceTemplate and MapperTemplate.
        private static void WriteNewAttribute(CodeWriter w, BoldAttributeSpec spec)
        {
            WriteContentInterface(w, spec);
            w.Line();
            w.Line($"partial class {spec.ClassName}");
            w.Open();
            w.Line($"/// <summary>The content (stream) name of {spec.ExpressionName}.</summary>");
            w.Line($"public const string {spec.ContentNameConstant} = {Literal(spec.ContentName)};");
            foreach (BoldFieldSpec field in spec.Fields)
            {
                w.Line();
                w.Line($"private {field.TypeName} f{field.Name} = {field.InitialValue};");
            }

            foreach (BoldFieldSpec field in spec.Fields)
            {
                WriteFieldMembers(w, spec, field);
            }

            WriteAttributeAssignment(w, spec);
            w.Line();
            w.Line("/// <summary>The fields are empty again.</summary>");
            w.Line("protected override void FreeContent()");
            w.Open();
            w.Line("base.FreeContent();");
            foreach (BoldFieldSpec field in spec.Fields)
            {
                w.Line($"f{field.Name} = {field.InitialValue};");
            }

            w.Close();
            w.Line();
            w.Line($"/// <summary>The proxy that gives the attribute as {spec.InterfaceName}.</summary>");
            w.Line($"protected override global::System.Type ProxyClass() => typeof({spec.ProxyName});");
            w.Line();
            w.Line($"/// <summary>Gives the attribute as {spec.InterfaceName}, through its proxy.</summary>");
            w.Line("public override bool ProxyInterface(global::System.Type IId, global::Bold.TBoldDomainElementProxyMode Mode, out object? Obj)");
            w.Open();
            w.Line($"if (IId == typeof({spec.InterfaceName}))");
            w.Open();
            w.Line($"return RetrieveProxyInterface(IId, Mode, out Obj, {Literal(spec.InterfaceName)});");
            w.Close();
            w.Line();
            w.Line("return base.ProxyInterface(IId, Mode, out Obj);");
            w.Close();
            WriteTypeNameMapping(w, spec, spec.ContentName, spec.MapperName, "", "");
            WriteRegistration(w, spec, w2 =>
                w2.Line($"global::Bold.BoldFreeStandingValueFactories.FreeStandingValueFactory!.RegisterFreeStandingClass({spec.ContentNameConstant}, typeof({spec.FreeStandingName}));"));
            w.Close();
            w.Line();
            WriteProxy(w, spec);
            w.Line();
            WriteFreeStandingValue(w, spec);
            if (spec.GenerateMapper)
            {
                w.Line();
                WriteMapper(w, spec);
            }
        }

        private static void WriteContentInterface(CodeWriter w, BoldAttributeSpec spec)
        {
            w.Line($"/// <summary>A {spec.ExpressionName} value: {string.Join(", ", spec.Fields.Select(f => f.Name))}.</summary>");
            w.Line($"{spec.Accessibility} interface {spec.InterfaceName} : global::Bold.IBoldNullableValue");
            w.Open();
            foreach (BoldFieldSpec field in spec.Fields)
            {
                w.Line($"{field.TypeName} Get{field.Name}Content();");
                w.Line($"void Set{field.Name}Content({field.TypeName} Value);");
                w.Line();
                w.Line($"{field.TypeName} {field.Name}");
                w.Open();
                w.Line($"get => Get{field.Name}Content();");
                w.Line($"set => Set{field.Name}Content(value);");
                w.Close();
                if (field != spec.Fields[spec.Fields.Count - 1])
                {
                    w.Line();
                }
            }

            w.Close();
        }

        private static void WriteFieldMembers(CodeWriter w, BoldAttributeSpec spec, BoldFieldSpec field)
        {
            string n = field.Name;
            string t = field.TypeName;
            w.Line();
            if (field.Readable)
            {
                w.Line($"/// <summary>{n}, once the attribute may be read and has a value.</summary>");
                w.Line($"protected {t} GetAs{n}()");
                w.Open();
                w.Line("global::Bold.BoldSystem.BoldClearLastFailure();");
                w.Line("if (!CanRead(null))");
                w.Open();
                w.Line($"global::Bold.BoldSystem.BoldRaiseLastFailure(this, \"GetAs{n}\", \"\");");
                w.Close();
                w.Line();
                w.Line("EnsureNotNull(); // ensures current");
                w.Line($"return f{n};");
                w.Close();
                w.Line();
            }

            w.Line($"internal {t} Get{n}Content() => f{n};");
            w.Line();
            w.Line($"/// <summary>Sets the content of {n} (without asking), telling subscribers when it changes.</summary>");
            w.Line($"internal void Set{n}Content({t} NewValue)");
            w.Open();
            w.Line($"if (BoldPersistenceState == global::Bold.TBoldValuePersistenceState.bvpsInvalid || ContentIsNull || !global::System.Collections.Generic.EqualityComparer<{t}>.Default.Equals(f{n}, NewValue))");
            w.Open();
            w.Line("PreChange();");
            w.Line($"f{n} = NewValue;");
            w.Line("SetToNonNull();");
            w.Line("Changed(global::Bold.BoldSubscription.beValueChanged, new object?[] { NewValue });");
            w.Close();
            w.Close();
            if (field.Writable)
            {
                w.Line();
                w.Line($"protected void SetAs{n}({t} Value) => SetDataValue{n}(Value);");
                w.Line();
                w.Line($"/// <summary>Whether {n} may be set to the value; a subclass can say no.</summary>");
                w.Line($"protected virtual bool MaySet{n}({t} NewValue, global::Bold.TBoldSubscriber? Subscriber) => true;");
                w.Line();
                w.Line($"/// <summary>Whether {n} may be set to the value: the attribute and its subscribers agree.</summary>");
                w.Line($"public bool CanSet{n}({t} Value, global::Bold.TBoldSubscriber? Subscriber) =>");
                w.Line($"    MaySet{n}(Value, Subscriber) && SendQuery(global::Bold.BoldSystem.bqMaySetValue, new object?[] {{ Value }}, Subscriber);");
                w.Line();
                w.Line($"private void SetDataValue{n}({t} Value)");
                w.Open();
                w.Line("global::Bold.BoldSystem.BoldClearLastFailure();");
                w.Line($"if (!CanSet{n}(Value, null))");
                w.Open();
                w.Line($"global::Bold.BoldSystem.BoldRaiseLastFailure(this, \"SetDataValue{n}\", \"\");");
                w.Close();
                w.Line();
                w.Line($"if (IsNull || !global::System.Collections.Generic.EqualityComparer<{t}>.Default.Equals(f{n}, Value))");
                w.Open();
                w.Line("if (!StartModify())");
                w.Open();
                w.Line($"global::Bold.BoldSystem.BoldRaiseLastFailure(this, \"SetDataValue{n}\", \"\");");
                w.Close();
                w.Line();
                w.Line("try");
                w.Open();
                w.Line($"Set{n}Content(Value);");
                w.Line("EndModify();");
                w.Close();
                w.Line("catch");
                w.Open();
                w.Line("FailModify();");
                w.Line("throw;");
                w.Close();
                w.Close();
                w.Close();
            }

            if (field.Readable || field.Writable)
            {
                w.Line();
                w.Line($"/// <summary>{n} of the value.</summary>");
                w.Line($"public {t} As{n}");
                w.Open();
                if (field.Readable)
                {
                    w.Line($"get => GetAs{n}();");
                }

                if (field.Writable)
                {
                    w.Line($"set => SetAs{n}(value);");
                }

                w.Close();
            }
        }

        // The template's interfaced class methods: AssignValue, AssignContentValue and Assign.
        private static void WriteAttributeAssignment(CodeWriter w, BoldAttributeSpec spec)
        {
            BoldFieldSpec[] writable = spec.Fields.Where(f => f.Writable).ToArray();
            w.Line();
            w.Line($"/// <summary>Takes the value of a {spec.InterfaceName}, as a user's change.</summary>");
            w.Line("protected override void AssignValue(global::Bold.IBoldValue Source)");
            w.Open();
            w.Line($"if (Source is {spec.InterfaceName} s)");
            w.Open();
            foreach (BoldFieldSpec field in writable)
            {
                w.Line($"SetDataValue{field.Name}(s.{field.Name});");
            }

            w.Close();
            w.Line("else");
            w.Open();
            w.Line("throw new global::Bold.EBold(global::Bold.SysUtils.Format(\"%s.AssignValue: unknown type of source\", GetType().Name));");
            w.Close();
            w.Close();
            w.Line();
            w.Line($"/// <summary>Takes the content of a {spec.InterfaceName} (null when it is null).</summary>");
            w.Line("protected override void AssignContentValue(global::Bold.IBoldValue Source)");
            w.Open();
            w.Line($"if (Source is {spec.InterfaceName} s)");
            w.Open();
            w.Line("if (s.IsNull)");
            w.Open();
            w.Line("SetContentToNull();");
            w.Close();
            w.Line("else");
            w.Open();
            foreach (BoldFieldSpec field in spec.Fields)
            {
                w.Line($"Set{field.Name}Content(s.{field.Name});");
            }

            w.Close();
            w.Close();
            w.Line("else");
            w.Open();
            w.Line("throw new global::Bold.EBold(global::Bold.SysUtils.Format(\"%s.AssignContentValue: unknown type of source\", GetType().Name));");
            w.Close();
            w.Close();
            w.Line();
            w.Line($"/// <summary>Takes the value of another {spec.ClassName}.</summary>");
            w.Line("public override void Assign(global::Bold.TBoldElement? Source)");
            w.Open();
            w.Line($"if (Source is {spec.ClassName} other)");
            w.Open();
            w.Line("if (other.IsNull)");
            w.Open();
            w.Line("SetToNull();");
            w.Close();
            w.Line("else");
            w.Open();
            foreach (BoldFieldSpec field in writable)
            {
                w.Line($"SetDataValue{field.Name}(other.f{field.Name});");
            }

            w.Close();
            w.Close();
            w.Line("else");
            w.Open();
            w.Line("base.Assign(Source);");
            w.Close();
            w.Close();
        }

        private static void WriteProxy(CodeWriter w, BoldAttributeSpec spec)
        {
            w.Line($"/// <summary>Gives a {spec.ClassName} as {spec.InterfaceName}.</summary>");
            w.Line($"{spec.Accessibility} class {spec.ProxyName}(global::Bold.TBoldDomainElement aProxedElement, global::Bold.TBoldDomainElementProxyMode aMode)");
            w.Line($"    : global::Bold.TBoldAttribute_Proxy(aProxedElement, aMode), {spec.InterfaceName}");
            w.Open();
            w.Line($"protected {spec.ClassName} Proxed{spec.ExpressionName} => ({spec.ClassName})ProxedElement;");
            foreach (BoldFieldSpec field in spec.Fields)
            {
                w.Line();
                w.Line($"public {field.TypeName} Get{field.Name}Content() => Proxed{spec.ExpressionName}.Get{field.Name}Content();");
                w.Line();
                w.Line($"public void Set{field.Name}Content({field.TypeName} Value) => Proxed{spec.ExpressionName}.Set{field.Name}Content(Value);");
            }

            w.Close();
        }

        // InterfaceTemplate: the free-standing value (a value space's value of the content).
        private static void WriteFreeStandingValue(CodeWriter w, BoldAttributeSpec spec)
        {
            w.Line($"/// <summary>A {spec.ExpressionName} value in a value space.</summary>");
            w.Line($"{spec.Accessibility} class {spec.FreeStandingName} : global::Bold.TBoldFreeStandingNullableValue, {spec.InterfaceName}");
            w.Open();
            foreach (BoldFieldSpec field in spec.Fields)
            {
                w.Line($"private {field.TypeName} f{field.Name} = {field.InitialValue};");
            }

            foreach (BoldFieldSpec field in spec.Fields)
            {
                w.Line();
                w.Line($"public {field.TypeName} Get{field.Name}Content() => f{field.Name};");
                w.Line();
                w.Line($"public void Set{field.Name}Content({field.TypeName} NewValue)");
                w.Open();
                w.Line($"f{field.Name} = NewValue;");
                w.Line("SetToNonNull();");
                w.Close();
            }

            w.Line();
            w.Line($"public override string GetStreamName() => {spec.ClassName}.{spec.ContentNameConstant};");
            w.Line();
            w.Line("protected override void AssignContentValue(global::Bold.IBoldValue Source)");
            w.Open();
            w.Line($"if (Source is not {spec.InterfaceName} s)");
            w.Open();
            w.Line("throw new global::Bold.EBold(global::Bold.SysUtils.Format(\"%s.AssignContentValue: unknown type of source\", GetType().Name));");
            w.Close();
            w.Line();
            w.Line("if (s.IsNull)");
            w.Open();
            w.Line("SetContentToNull();");
            w.Close();
            w.Line("else");
            w.Open();
            foreach (BoldFieldSpec field in spec.Fields)
            {
                w.Line($"Set{field.Name}Content(s.{field.Name});");
            }

            w.Close();
            w.Close();
            foreach (BoldFieldSpec field in spec.Fields)
            {
                w.Line();
                w.Line($"public {field.TypeName} {field.Name}");
                w.Open();
                w.Line($"get => Get{field.Name}Content();");
                w.Line($"set => Set{field.Name}Content(value);");
                w.Close();
            }

            w.Close();
        }

        // MapperTemplate: one column a field, in the table of the attribute's class.
        private static void WriteMapper(CodeWriter w, BoldAttributeSpec spec)
        {
            string mapper = spec.MapperName;
            w.Line($"/// <summary>Stores {spec.ExpressionName} in one column a field ({string.Join(", ", spec.Fields.Select(f => f.Name))}). A partial class: add overrides of your own.</summary>");
            w.Line($"{spec.Accessibility} partial class {mapper} : global::Bold.TBoldMemberDefaultMapper");
            w.Open();
            w.Line($"public {mapper}(global::Bold.TMoldMember? Moldmember, global::Bold.TMoldClass MoldClass, global::Bold.TBoldObjectPersistenceMapper Owner, int MemberIndex,");
            w.Line("    global::Bold.TBoldTypeNameDictionary TypeNameDictionary)");
            w.Line("    : base(Moldmember, MoldClass, Owner, MemberIndex, TypeNameDictionary)");
            w.Open();
            w.Close();
            w.Line();
            w.Line($"/// <summary>The mapper stores the content {spec.ContentName}.</summary>");
            w.Line($"public static new bool CanStore(string ContentName) => global::Bold.SysUtils.AnsiCompareText(ContentName, {spec.ClassName}.{spec.ContentNameConstant}) == 0;");
            w.Line();
            w.Line($"protected override int GetColumnCount() => {spec.Fields.Count};");
            w.Line();
            w.Line("protected override string GetColumnTypeAsSQL(int ColumnIndex) => ColumnIndex switch");
            w.Open();
            for (int i = 0; i < spec.Fields.Count; i++)
            {
                w.Line($"{i} => {SqlType(spec.Fields[i].Storage)},");
            }

            w.Line("_ => SystemPersistenceMapper.SQLDataBaseConfig.ColumnTypeForInteger,");
            w.CloseWith("};");
            w.Line();
            w.Line("protected override global::Bold.TFieldType GetColumnBDEFieldType(int ColumnIndex) => ColumnIndex switch");
            w.Open();
            for (int i = 0; i < spec.Fields.Count; i++)
            {
                w.Line($"{i} => global::Bold.TFieldType.{FieldType(spec.Fields[i].Storage)},");
            }

            w.Line("_ => base.GetColumnBDEFieldType(ColumnIndex),");
            w.CloseWith("};");
            w.Line();
            w.Line("protected override int GetColumnSize(int ColumnIndex) => ColumnIndex switch");
            w.Open();
            for (int i = 0; i < spec.Fields.Count; i++)
            {
                w.Line($"{i} => {(spec.Fields[i].Storage == BoldFieldStorage.String ? "255" : "0")},");
            }

            w.Line("_ => base.GetColumnSize(ColumnIndex),");
            w.CloseWith("};");
            w.Line();
            w.Line("protected override bool CompareField(global::Bold.IBoldObjectContents ObjectContent, global::Bold.IBoldField Field, int ColumnIndex, global::Bold.IBoldValueSpace ValueSpace,");
            w.Line("    global::Bold.TBoldIDTranslationList TranslationList)");
            w.Open();
            w.Line($"var aValue = ({spec.InterfaceName})GetValue(ObjectContent)!;");
            w.Line("if (CheckEitherNull(Field, aValue, out bool equal))");
            w.Open();
            w.Line("return equal;");
            w.Close();
            w.Line();
            w.Line("return ColumnIndex switch");
            w.Open();
            for (int i = 0; i < spec.Fields.Count; i++)
            {
                w.Line($"{i} => global::System.Collections.Generic.EqualityComparer<{spec.Fields[i].TypeName}>.Default.Equals({FieldRead(spec.Fields[i].Storage)}, aValue.{spec.Fields[i].Name}),");
            }

            w.Line("_ => false,");
            w.CloseWith("};");
            w.Close();
            w.Line();
            w.Line("public override void ValueFromField(global::Bold.TBoldObjectId OwningObjectId, global::Bold.IBoldObjectContents ObjectContent, global::Bold.IBoldValueSpace ValueSpace,");
            w.Line("    global::Bold.TBoldIDTranslationList TranslationList, global::Bold.IBoldField Field, int ColumnIndex)");
            w.Open();
            w.Line($"var aValue = ({spec.InterfaceName})GetEnsuredValue(ObjectContent)!;");
            w.Line("if (Field.IsNull)");
            w.Open();
            w.Line("aValue.SetContentToNull();");
            w.Line("return;");
            w.Close();
            w.Line();
            w.Line("switch (ColumnIndex)");
            w.Open();
            for (int i = 0; i < spec.Fields.Count; i++)
            {
                w.Line($"case {i}:");
                w.Line($"    aValue.{spec.Fields[i].Name} = {FieldRead(spec.Fields[i].Storage)};");
                w.Line("    break;");
            }

            w.Line("default:");
            w.Line("    base.ValueFromField(OwningObjectId, ObjectContent, ValueSpace, TranslationList, Field, ColumnIndex);");
            w.Line("    break;");
            w.Close();
            w.Close();
            w.Line();
            w.Line("public override void ValueToParam(global::Bold.IBoldObjectContents ObjectContent, global::Bold.IBoldParameter Param, int ColumnIndex,");
            w.Line("    global::Bold.TBoldIDTranslationList TranslationList)");
            w.Open();
            w.Line($"var aValue = ({spec.InterfaceName})GetEnsuredValue(ObjectContent)!;");
            w.Line("if (aValue.IsNull)");
            w.Open();
            w.Line("SetParamToNullWithDataType(Param, GetColumnBDEFieldType(ColumnIndex));");
            w.Line("return;");
            w.Close();
            w.Line();
            w.Line("switch (ColumnIndex)");
            w.Open();
            for (int i = 0; i < spec.Fields.Count; i++)
            {
                w.Line($"case {i}:");
                w.Line($"    {ParamWrite(spec.Fields[i].Storage)} = aValue.{spec.Fields[i].Name};");
                w.Line("    break;");
            }

            w.Line("default:");
            w.Line("    base.ValueToParam(ObjectContent, Param, ColumnIndex, TranslationList);");
            w.Line("    break;");
            w.Close();
            w.Close();
            w.Line();
            w.Line("/// <summary>Registers the mapper with Bold when the assembly is first used.</summary>");
            w.Line("[global::System.Runtime.CompilerServices.ModuleInitializer]");
            w.Line("internal static void RegisterBoldMapper() =>");
            w.Line($"    global::Bold.BoldPMapperLists.BoldMemberPersistenceMappers().AddDescriptor(typeof({mapper}), global::Bold.TBoldAbstractionLevel.alConcrete);");
            w.Close();
        }

        private static void WriteTypeNameMapping(CodeWriter w, BoldAttributeSpec spec, string contentName, string mapperName, string accessor, string nativeType)
