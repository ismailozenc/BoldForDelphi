using System.Text;
using Bold.PortTool.Delphi;

namespace Bold.PortTool.Port;

/// <summary>
/// Writes CSharp/port/PORT_STATUS.md (all units) and CSharp/port/units/&lt;Unit&gt;.md (every symbol of one unit, linked to
/// its Delphi declaration and body, its C# declaration and the tests that cover it).
/// </summary>
public sealed class ReportWriter(PortAnalysis analysis)
{
    private const string StatusFile = "CSharp/port/PORT_STATUS.md";

    private static readonly Indicator[] Order =
    [
        Indicator.Verified, Indicator.Ported, Indicator.Replaced, Indicator.Partial, Indicator.Stub, Indicator.Failing,
        Indicator.NotStarted, Indicator.Dropped,
    ];

    public static string Icon(Indicator indicator) => indicator switch
    {
        Indicator.Verified => "✅",
        Indicator.Failing => "❌",
        Indicator.Ported => "🟢",
        Indicator.Replaced => "🔵",
        Indicator.Partial => "🟡",
        Indicator.Stub => "🟠",
        Indicator.NotStarted => "⚪",
        _ => "⚫",
    };

    public static string Label(Indicator indicator) => indicator switch
    {
        Indicator.Verified => "verified",
        Indicator.Failing => "failing",
        Indicator.Ported => "ported",
        Indicator.Replaced => "replaced",
        Indicator.Partial => "partial",
        Indicator.Stub => "stub",
        Indicator.NotStarted => "not started",
        _ => "dropped",
    };

    public static string Badge(Indicator indicator) => $"{Icon(indicator)} {Label(indicator)}";

    /// <summary>Writes every report; returns the files written. Unit pages of units that no longer exist are removed.</summary>
    public List<string> WriteAll()
    {
        var written = new List<string>();
        var layout = analysis.Layout;
        Directory.CreateDirectory(layout.UnitsDir);
        var expected = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var unit in analysis.Units)
        {
            string page = RepoLayout.UnitPage(unit.Unit.Name);
            expected.Add(Path.GetFileName(page));
            if (WriteIfChanged(layout.Full(page), UnitPage(unit)))
            {
                written.Add(page);
            }
        }

        foreach (string stale in Directory.EnumerateFiles(layout.UnitsDir, "*.md").Where(f => !expected.Contains(Path.GetFileName(f))))
        {
            File.Delete(stale);
            written.Add(layout.Relative(stale) + " (removed)");
        }

        if (WriteIfChanged(layout.StatusFile, StatusPage()))
        {
            written.Add(StatusFile);
        }

        return written;
    }

    public static bool WriteIfChanged(string path, string content)
    {
        if (File.Exists(path) && File.ReadAllText(path) == content)
        {
            return false;
        }

        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content, new UTF8Encoding(false));
        return true;
    }

    private string GeneratedNote(string fromFile) =>
        $"> Generated by Bold.PortTool from the Delphi source, the `[Delphi]` and `[Covers]` attributes in the C# code, " +
        $"[port-map.json]({Md.Href(fromFile, "CSharp/port/port-map.json")}) and the test results. Do not edit it by hand; " +
        $"see [PORTING.md]({Md.Href(fromFile, "CSharp/PORTING.md")}).";

    private static string Legend() =>
        "| Indicator | Meaning |\n|---|---|\n" +
        $"| {Badge(Indicator.Verified)} | Ported or replaced, and every test that covers it passed |\n" +
        $"| {Badge(Indicator.Ported)} | Ported with the same behaviour; no passing test covers it yet |\n" +
        $"| {Badge(Indicator.Replaced)} | A .NET feature or a new design does the job; the note says which |\n" +
        $"| {Badge(Indicator.Partial)} | Part of the behaviour is ported; the note says what is missing |\n" +
        $"| {Badge(Indicator.Stub)} | Declared with the Delphi name; throws NotImplementedException |\n" +
        $"| {Badge(Indicator.Failing)} | A test that covers it failed |\n" +
        $"| {Badge(Indicator.NotStarted)} | No C# yet |\n" +
        $"| {Badge(Indicator.Dropped)} | Not ported on purpose; the note says why |\n";

    private static string Bar(int done, int total)
    {
        if (total == 0)
        {
            return "";
        }

        int percent = (int)Math.Round(100.0 * done / total);
        int filled = (int)Math.Round(10.0 * done / total);
        return $"{new string('▰', filled)}{new string('▱', 10 - filled)} {percent}%";
    }

    private string ResultsLine()
    {
        var results = analysis.Results;
        return results.IsEmpty
            ? "No test results were found, so nothing shows as verified. Run the tests with a results logger first (see PORTING.md)."
            : $"Test results: {results.Count} test methods from {string.Join(", ", results.Sources.Select(s => $"`{s}`"))}.";
    }

    public string StatusPage()
    {
        var text = new StringBuilder();
        text.Append("# Bold C# port status\n\n");
        text.Append(GeneratedNote(StatusFile)).Append("\n\n");
        text.Append(ResultsLine()).Append("\n\n");
        text.Append("Each Delphi unit has a page that lists every type, method, property, routine and constant with links to the Delphi " +
                    "declaration, the C# code and the tests. Each Delphi unit links back here from its `unit` line, and each source folder's " +
                    "FOLDER_INFO.md lists where its units went.\n\n");
        text.Append(Legend()).Append('\n');
        AppendTotals(text);
        AppendGroups(text, "Milestones", u => u.Map?.Milestone ?? "(none)", key => analysis.Map.MilestoneTitle(key == "(none)" ? null : key),
            key => analysis.Map.MilestoneOrder(key == "(none)" ? null : key));
        AppendGroups(text, "Projects", u => u.Map?.Project ?? "(none)", key => key == "(none)" ? "not decided yet" : key, key => key == "(none)" ? 1 : 0);
        AppendUnits(text);
        AppendProblems(text, StatusFile);
        return text.ToString();
    }

    /// <summary>A short summary for the CI job page: totals, milestones and problems.</summary>
    public string Summary()
    {
        var text = new StringBuilder();
        text.Append("## Bold C# port status\n\n");
        text.Append(ResultsLine()).Append("\n\n");
        AppendTotals(text);
        AppendGroups(text, "Milestones", u => u.Map?.Milestone ?? "(none)", key => analysis.Map.MilestoneTitle(key == "(none)" ? null : key),
            key => analysis.Map.MilestoneOrder(key == "(none)" ? null : key));
        var started = analysis.Units.Where(u => !u.IsDropped && (u.Started > 0 || u.Done > 0)).ToList();
        if (started.Count > 0)
        {
            text.Append("### Units in progress\n\n| Unit | Status | Done | Verified |\n|---|---|---|---|\n");
            foreach (var unit in started)
            {
                text.Append($"| {unit.Unit.Name} | {Badge(unit.Overall)} | {unit.Done}/{unit.Symbols.Count} | {unit.Verified} |\n");
            }

            text.Append('\n');
        }

        AppendProblems(text, null);
        return text.ToString();
    }

    private void AppendTotals(StringBuilder text)
    {
        var ported = analysis.Units.Where(u => !u.IsDropped).ToList();
        var symbols = ported.SelectMany(u => u.Symbols).ToList();
        int dropped = analysis.Units.Count(u => u.IsDropped);
        text.Append("## Totals\n\n");
        text.Append($"{analysis.Units.Count} Delphi units: {ported.Count} to port, {dropped} not ported. ");
        text.Append($"The units to port declare {symbols.Count} symbols. ");
        text.Append($"{analysis.Markers.Count} `[Delphi]` markers in the C# code; {analysis.TestMethodCount} test methods.\n\n");
        text.Append("| Indicator | Symbols | Share |\n|---|---:|---|\n");
        foreach (var indicator in Order)
        {
            int count = symbols.Count(s => s.Indicator == indicator);
            text.Append($"| {Badge(indicator)} | {count} | {Bar(count, symbols.Count)} |\n");
        }

        text.Append('\n');
    }

    private void AppendGroups(StringBuilder text, string title, Func<UnitStatus, string> key, Func<string, string> label, Func<string, int> order)
    {
        text.Append($"## {title}\n\n| {title[..^1]} | Units | Symbols | Done | Verified | Progress |\n|---|---:|---:|---:|---:|---|\n");
        foreach (var group in analysis.Units.Where(u => !u.IsDropped).GroupBy(key).OrderBy(g => order(g.Key)).ThenBy(g => g.Key, StringComparer.Ordinal))
        {
            int total = group.Sum(u => u.Symbols.Count);
            int done = group.Sum(u => u.Done);
            int verified = group.Sum(u => u.Verified);
            text.Append($"| {Md.Escape(label(group.Key))} | {group.Count()} | {total} | {done} | {verified} | {Bar(done, total)} |\n");
        }

        text.Append('\n');
    }

    private void AppendUnits(StringBuilder text)
    {
        text.Append("## Units\n\n");
        text.Append("| Unit | Status | Done | Verified | Project | Milestone | Delphi | C# |\n|---|---|---:|---:|---|---|---|---|\n");
        foreach (var unit in analysis.Units
                     .OrderBy(u => u.IsDropped)
                     .ThenBy(u => analysis.Map.MilestoneOrder(u.Map?.Milestone))
                     .ThenBy(u => u.Unit.File, StringComparer.Ordinal))
        {
            string csharp = CSharpCell(unit, StatusFile);
            string project = unit.IsDropped ? $"not ported: {Md.Escape(unit.Map!.Drop!)}" : Md.Escape(unit.Map?.Project ?? "");
            text.Append($"| {Md.Link(unit.Unit.Name, StatusFile, RepoLayout.UnitPage(unit.Unit.Name))} | {Badge(unit.Overall)} | " +
                        $"{unit.Done}/{unit.Symbols.Count} | {unit.Verified} | {project} | {Md.Escape(unit.Map?.Milestone ?? "")} | " +
                        $"{Md.Link(unit.Unit.File, StatusFile, unit.Unit.File)} | {csharp} |\n");
        }

        text.Append('\n');
    }

    private static string CSharpCell(UnitStatus unit, string fromFile)
    {
        if (unit.CSharpFiles.Count > 0)
        {
            return string.Join("<br>", unit.CSharpFiles.Select(f => Md.Link(f["CSharp/".Length..], fromFile, f)));
        }

        string? planned = unit.Map?.CSharpFile;
        return planned is null ? "" : $"planned: {Md.Escape(planned["CSharp/".Length..])}";
    }

    private void AppendProblems(StringBuilder text, string? fromFile)
    {
        var problems = analysis.Problems;
        text.Append("## Problems\n\n");
        if (problems.Count == 0)
        {
            text.Append("None: every marker and test link resolves.\n");
            return;
        }

        text.Append($"{problems.Count(p => p.Severity == Severity.Error)} errors, {problems.Count(p => p.Severity == Severity.Warning)} warnings.\n\n");
        foreach (var problem in problems.Take(200))
        {
            string where = problem.Location;
            if (fromFile is not null)
            {
                int colon = where.LastIndexOf(':');
                where = colon > 0 && int.TryParse(where[(colon + 1)..], out int line)
                    ? Md.Link(where, fromFile, where[..colon], line)
                    : Md.Link(where, fromFile, where);
            }

            text.Append($"- **{(problem.Severity == Severity.Error ? "error" : "warning")}** {where}: {Md.Escape(problem.Message)}\n");
        }

        if (problems.Count > 200)
        {
            text.Append($"- … and {problems.Count - 200} more; run the check command to see all.\n");
        }
    }

    public string UnitPage(UnitStatus unit)
    {
        var delphi = unit.Unit;
        string page = RepoLayout.UnitPage(delphi.Name);
        var text = new StringBuilder();
        text.Append($"# {delphi.Name}\n\n");
        text.Append(GeneratedNote(page)).Append("\n\n");
        text.Append("| | |\n|---|---|\n");
        text.Append($"| Delphi | {Md.CodeLink(delphi.File, page, delphi.File)} ({delphi.Lines} lines) |\n");
        if (unit.IsDropped)
        {
            text.Append($"| C# | not ported: {Md.Escape(unit.Map!.Drop!)} |\n");
        }
        else
        {
            string csharp = unit.CSharpFiles.Count > 0
                ? string.Join("<br>", unit.CSharpFiles.Select(f => Md.CodeLink(f, page, f)))
                : unit.Map?.CSharpFile is { } planned ? $"not started; planned as {Md.Code(planned)}" : "not planned yet";
            text.Append($"| C# | {csharp} |\n");
            text.Append($"| Project | {Md.Escape(unit.Map?.Project ?? "not decided")} |\n");
        }

        if (unit.Map?.Milestone is not null)
        {
            text.Append($"| Milestone | {Md.Escape(analysis.Map.MilestoneTitle(unit.Map.Milestone))} |\n");
        }

        text.Append(unit.IsDropped
            ? $"| Status | {Badge(Indicator.Dropped)}: {unit.Symbols.Count} symbols |\n"
            : $"| Status | {Badge(unit.Overall)}: {unit.Done} of {unit.Symbols.Count} symbols done, {unit.Verified} verified |\n");
        if (unit.Map?.Note is { } note)
        {
            text.Append($"| Note | {Md.Escape(note)} |\n");
        }

        text.Append('\n');
        if (unit.IsDropped)
        {
            AppendDroppedUnit(text, unit, page);
        }
        else
        {
            text.Append(Counts(unit)).Append("\n\n");
            var unitLevel = unit.Symbols.Where(s => s.Symbol.Owner is null).ToList();
            if (unitLevel.Count > 0)
            {
                text.Append("## Unit level\n\nTypes, routines, constants, variables and the initialization and finalization sections.\n\n");
                AppendSymbolTable(text, unitLevel, page, ownerPrefix: false);
            }

            foreach (var owner in unit.Symbols.Where(s => s.Symbol.Owner is not null).GroupBy(s => s.Symbol.Owner!, StringComparer.OrdinalIgnoreCase))
            {
                var type = unit.Symbols.FirstOrDefault(s => s.Symbol.Owner is null && string.Equals(s.Symbol.Name, owner.Key, StringComparison.OrdinalIgnoreCase));
                text.Append($"## {owner.Key}\n\n");
                if (type is not null)
                {
                    text.Append($"{type.Symbol.KindText} at {Md.Link($"line {type.Symbol.Line}", page, type.Symbol.File, type.Symbol.Line)}; " +
                                $"{Badge(type.Indicator)}{CSharpRef(type, page, prefix: ", C# ")}.\n\n");
                }

                AppendSymbolTable(text, owner.ToList(), page, ownerPrefix: true);
            }

            if (unit.Additions.Count > 0)
            {
                text.Append("## C# additions\n\nDeclared in this unit's C# files with no Delphi counterpart (helpers, .NET plumbing).\n\n");
                foreach (var addition in unit.Additions)
                {
                    text.Append($"- {Md.CodeLink(addition.FullName, page, addition.File, addition.Line)} ({addition.KindText})\n");
                }

                text.Append('\n');
            }
        }

        AppendDependencies(text, delphi, page);
        var problems = analysis.Problems.Where(p => unit.CSharpFiles.Any(f => p.Location.StartsWith(f, StringComparison.Ordinal)) ||
                                                    p.Location.StartsWith(delphi.File, StringComparison.Ordinal)).ToList();
        if (problems.Count > 0)
        {
            text.Append("## Problems\n\n");
            foreach (var problem in problems)
            {
                text.Append($"- **{(problem.Severity == Severity.Error ? "error" : "warning")}** {Md.Escape(problem.Location)}: {Md.Escape(problem.Message)}\n");
            }

            text.Append('\n');
        }

        return text.ToString();
    }

    /// <summary>A unit that is not ported lists its types only; its members all share the unit's reason.</summary>
    private static void AppendDroppedUnit(StringBuilder text, UnitStatus unit, string page)
    {
        var types = unit.Symbols.Where(s => s.Symbol.IsType).ToList();
        text.Append("## Declared types\n\n");
        if (types.Count == 0)
        {
            text.Append($"None; its {unit.Symbols.Count} constants, routines and variables are not ported either.\n\n");
            return;
        }

        text.Append("The members of these types are not listed: nothing in this unit is ported.\n\n");
        foreach (var type in types)
        {
            int members = unit.Symbols.Count(s => string.Equals(s.Symbol.Owner, type.Symbol.Name, StringComparison.OrdinalIgnoreCase));
            text.Append($"- {Md.Code(type.Symbol.Name)} ({type.Symbol.KindText}, {Md.Link($"line {type.Symbol.Line}", page, type.Symbol.File, type.Symbol.Line)}" +
                        $"{(members > 0 ? $", {members} members" : "")})\n");
        }

        text.Append('\n');
    }

    private void AppendDependencies(StringBuilder text, DelphiUnit delphi, string page)
    {
        var uses = UnitNames(delphi.UsesInterface.Concat(delphi.UsesImplementation));
        var usedBy = UnitNames(analysis.Delphi.Units
            .Where(u => u.UsesInterface.Concat(u.UsesImplementation).Any(n => string.Equals(n, delphi.Name, StringComparison.OrdinalIgnoreCase)))
            .Select(u => u.Name));
        text.Append("## Dependencies\n\n");
        text.Append($"Uses {(uses.Count == 0 ? "no other Bold unit" : string.Join(", ", uses.Select(n => Md.Link(n, page, RepoLayout.UnitPage(n)))))}.\n\n");
        if (usedBy.Count == 0)
        {
            text.Append("No Bold unit uses it.\n\n");
        }
        else if (usedBy.Count <= 12)
        {
            text.Append($"Used by {string.Join(", ", usedBy.Select(n => Md.Link(n, page, RepoLayout.UnitPage(n))))}.\n\n");
        }
        else
        {
            text.Append($"<details><summary>Used by {usedBy.Count} units</summary>\n\n");
            text.Append(string.Join(", ", usedBy.Select(n => Md.Link(n, page, RepoLayout.UnitPage(n))))).Append("\n\n</details>\n\n");
        }
    }

    private List<string> UnitNames(IEnumerable<string> names) => names
        .Select(n => analysis.Delphi.Find(n))
        .Where(u => u is not null)
        .Select(u => u!.Name)
        .Distinct(StringComparer.OrdinalIgnoreCase)
        .ToList();

    private static string Counts(UnitStatus unit) =>
        string.Join(" · ", Order.Select(i => (Indicator: i, Count: unit.Count(i))).Where(x => x.Count > 0)
            .Select(x => $"{Icon(x.Indicator)} {x.Count} {Label(x.Indicator)}"));

    private void AppendSymbolTable(StringBuilder text, List<SymbolStatus> symbols, string page, bool ownerPrefix)
    {
        text.Append("| Delphi | Kind | Lines | C# | Status | Tests |\n|---|---|---|---|---|---|\n");
        foreach (var item in symbols)
        {
            var symbol = item.Symbol;
            string name = ownerPrefix ? symbol.Key[(symbol.Owner!.Length + 1)..] : symbol.Key;
            string kind = symbol.KindText;
            if (!string.IsNullOrEmpty(symbol.Visibility) && symbol.Visibility != "public")
            {
                kind += $", {symbol.Visibility}";
            }

            if (!symbol.InInterface && symbol.Owner is null)
            {
                kind += ", implementation";
            }

            string lines = Md.Link(symbol.Line.ToString(System.Globalization.CultureInfo.InvariantCulture), page, symbol.File, symbol.Line);
            if (symbol.ImplLine is int implLine && symbol.ImplFile is not null && (implLine != symbol.Line || symbol.ImplFile != symbol.File))
            {
                lines += $" · {Md.Link($"body {implLine}", page, symbol.ImplFile, implLine)}";
            }

            string state = Badge(item.Indicator);
            if (item.Via is not null)
            {
                state += $" (via {Md.Escape(item.Via)})";
            }

            if (!string.IsNullOrEmpty(item.Note))
            {
                state += $": {Md.Escape(item.Note)}";
            }

            text.Append($"| {Md.Code(name)} | {kind} | {lines} | {CSharpRef(item, page, prefix: "")} | {state} | {TestLinks(item, page)} |\n");
        }

        text.Append('\n');
    }

    private string CSharpRef(SymbolStatus status, string page, string prefix)
    {
        var marker = status.Marker;
        if (marker is null)
        {
            return "";
        }

        var home = analysis.HomeOf(marker);
        if (home is null)
        {
            return prefix + Md.CodeLink($"[assembly: Delphi] in {Path.GetFileName(marker.File)}", page, marker.File, marker.Line);
        }

        string name = home.Kind == Bold.PortTool.CSharp.CsDeclarationKind.Alias ? $"global using {home.Name}" : home.FullName;
        return prefix + Md.CodeLink(name, page, home.File, home.Line);
    }

    private string TestLinks(SymbolStatus status, string page)
    {
        if (status.Tests.Count == 0)
        {
            return "";
        }

        return string.Join("<br>", status.Tests.Take(5).Select(t =>
        {
            var outcome = analysis.Results.Outcome(t.ClassName, t.Method);
            string mark = outcome switch { TestOutcome.Passed => "✔ ", TestOutcome.Failed => "✘ ", _ => "" };
            return mark + Md.CodeLink(t.ShortName, page, t.File, t.Line);
        })) + (status.Tests.Count > 5 ? $"<br>… {status.Tests.Count - 5} more" : "");
    }
}
