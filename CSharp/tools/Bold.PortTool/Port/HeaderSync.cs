using System.Text;
using System.Text.RegularExpressions;

namespace Bold.PortTool.Port;

/// <summary>
/// Keeps the links in the source files themselves up to date:
/// the comment after "unit X;" in every Delphi unit (where the unit went),
/// the "C# port" block in every FOLDER_INFO.md of a Delphi folder (where each unit of the folder went),
/// and the "// Delphi:" and "// Port map:" header lines of every C# file that ports a unit (where it came from).
/// The Delphi comment shares the unit line, so no Delphi line numbers change.
/// </summary>
public sealed partial class HeaderSync(PortAnalysis analysis)
{
    public const string FolderBlockBegin = "<!-- BEGIN C# PORT: generated by Bold.PortTool, do not edit this block -->";
    public const string FolderBlockEnd = "<!-- END C# PORT -->";

    [GeneratedRegex(@"^(?<head>\s*unit\s+[\w.]+\s*;)(?<old>[ \t]*\{ C# port:[^}]*\})?", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant)]
    private static partial Regex UnitLineRegex();

    /// <summary>The comment that follows "unit X;" in the Delphi file.</summary>
    public static string UnitComment(PortMapUnit? map, string unit)
    {
        string page = RepoLayout.UnitPage(unit);
        if (map is null)
        {
            return $"{{ C# port: not in CSharp/port/port-map.json yet }}";
        }

        if (map.IsReplaced && map.CSharpFile is null)
        {
            return $"{{ C# port: replaced by .NET ({Clean(map.Replace!)}); see {page} }}";
        }

        if (map.IsDropped)
        {
            return $"{{ C# port: not ported ({Clean(map.Drop!)}); see {page} }}";
        }

        return map.CSharpFile is { } file
            ? $"{{ C# port: {file}; symbols and status: {page} }}"
            : $"{{ C# port: not planned yet; see {page} }}";
    }

    private static string Clean(string text) => text.Replace('}', ')').Replace('{', '(').Replace("\n", " ", StringComparison.Ordinal);

    /// <summary>Updates (or with <paramref name="write"/> false, only lists) the files whose links are out of date.</summary>
    public List<string> Run(bool write)
    {
        var changed = new List<string>();
        SyncDelphiUnits(write, changed);
        SyncFolderInfos(write, changed);
        SyncCSharpHeaders(write, changed);
        return changed;
    }

    private void SyncDelphiUnits(bool write, List<string> changed)
    {
        foreach (var unit in analysis.Units)
        {
            string path = analysis.Layout.Full(unit.Unit.File);
            byte[] bytes = File.ReadAllBytes(path);
            string text = Encoding.Latin1.GetString(bytes);
            int start = 0;
            for (int number = 1; number < unit.Unit.UnitLine && start >= 0; number++)
            {
                start = text.IndexOf('\n', start) is int nl && nl >= 0 ? nl + 1 : -1;
            }

            if (start < 0)
            {
                analysis.Problems.Add(new Problem(Severity.Error, unit.Unit.File, $"line {unit.Unit.UnitLine} not found"));
                continue;
            }

            int end = text.IndexOf('\n', start);
            if (end < 0)
            {
                end = text.Length;
            }

            string line = text[start..end];
            var match = UnitLineRegex().Match(line);
            if (!match.Success)
            {
                analysis.Problems.Add(new Problem(Severity.Error, $"{unit.Unit.File}:{unit.Unit.UnitLine}", "no \"unit Name;\" at the start of this line to link from"));
                continue;
            }

            string updated = match.Groups["head"].Value + " " + UnitComment(unit.Map, unit.Unit.Name) + line[match.Length..];
            if (updated == line)
            {
                continue;
            }

            changed.Add(unit.Unit.File);
            if (write)
            {
                File.WriteAllBytes(path, Encoding.Latin1.GetBytes(text[..start] + updated + text[end..]));
            }
        }
    }

    private void SyncFolderInfos(bool write, List<string> changed)
    {
        foreach (var folder in analysis.Units.GroupBy(u => u.Unit.Folder, StringComparer.Ordinal))
        {
            string infoFile = $"{folder.Key}/FOLDER_INFO.md";
            string path = analysis.Layout.Full(infoFile);
            if (!File.Exists(path))
            {
                analysis.Problems.Add(new Problem(Severity.Warning, folder.Key, "no FOLDER_INFO.md to list where the units went"));
                continue;
            }

            string text = File.ReadAllText(path);
            string newline = text.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
            string block = FolderBlock(infoFile, folder.OrderBy(u => u.Unit.File, StringComparer.Ordinal).ToList()).Replace("\n", newline, StringComparison.Ordinal);
            string updated;
            int begin = text.IndexOf(FolderBlockBegin, StringComparison.Ordinal);
            int finish = begin < 0 ? -1 : text.IndexOf(FolderBlockEnd, begin, StringComparison.Ordinal);
            if (begin >= 0 && finish >= 0)
            {
                updated = text[..begin] + block + text[(finish + FolderBlockEnd.Length)..];
            }
            else
            {
                string trimmed = text.TrimEnd('\r', '\n', ' ', '\t');
                updated = trimmed + newline + newline + block + newline;
            }

            if (updated == text)
            {
                continue;
            }

            changed.Add(infoFile);
            if (write)
            {
                File.WriteAllText(path, updated, new UTF8Encoding(HasBom(path)));
            }
        }
    }

    private string FolderBlock(string infoFile, List<UnitStatus> units)
    {
        var text = new StringBuilder();
        text.Append(FolderBlockBegin).Append('\n');
        text.Append("## C# port\n\n");
        text.Append("Where the units of this folder go in the C# port. Each unit page lists the unit's types, methods and constants " +
                    "with their port status and links to the C# code and its tests.\n\n");
        text.Append("| Unit | C# | Milestone |\n|---|---|---|\n");
        foreach (var unit in units)
        {
            string name = Md.Link(unit.Unit.Name, infoFile, RepoLayout.UnitPage(unit.Unit.Name));
            string target;
            if (unit.IsDropped)
            {
                target = $"not ported: {Md.Escape(unit.Map!.Drop!)}";
            }
            else if (unit.Map?.IsReplaced == true && unit.Map.CSharpFile is null)
            {
                target = $"replaced by .NET: {Md.Escape(unit.Map.Replace!)}";
            }
            else if (unit.Map?.CSharpFile is { } file)
            {
                string shown = $"{unit.Map.Project}: {file[$"CSharp/src/{unit.Map.Project}/".Length..]}";
                target = File.Exists(analysis.Layout.Full(file)) ? Md.Link(shown, infoFile, file) : $"{Md.Escape(shown)} (not started)";
            }
            else
            {
                target = "not planned yet";
            }

            text.Append($"| {name} | {target} | {Md.Escape(analysis.Map.MilestoneTitle(unit.Map?.Milestone))} |\n");
        }

        text.Append(FolderBlockEnd);
        return text.ToString();
    }

    private void SyncCSharpHeaders(bool write, List<string> changed)
    {
        foreach (var file in analysis.CSharp.Files.Where(f => f.Path.StartsWith("CSharp/src/", StringComparison.Ordinal)))
        {
            var unit = analysis.Delphi.Find(file.UnitName);
            if (unit is null)
            {
                continue;
            }

            string path = analysis.Layout.Full(file.Path);
            bool bom = HasBom(path);
            string text = File.ReadAllText(path);
            string newline = text.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
            string header = $"// Delphi: {unit.File}{newline}// Port map: {RepoLayout.UnitPage(unit.Name)}{newline}";
            string body = text;
            foreach (string prefix in new[] { "// Delphi:", "// Port map:" })
            {
                if (body.StartsWith(prefix, StringComparison.Ordinal))
                {
                    int nl = body.IndexOf('\n');
                    body = nl < 0 ? "" : body[(nl + 1)..];
                }
            }

            string updated = header + body;
            if (updated == text)
            {
                continue;
            }

            changed.Add(file.Path);
            if (write)
            {
                File.WriteAllText(path, updated, new UTF8Encoding(bom));
            }
        }
    }

    private static bool HasBom(string path)
    {
        using var stream = File.OpenRead(path);
        Span<byte> start = stackalloc byte[3];
        return stream.Read(start) == 3 && start[0] == 0xEF && start[1] == 0xBB && start[2] == 0xBF;
    }
}
